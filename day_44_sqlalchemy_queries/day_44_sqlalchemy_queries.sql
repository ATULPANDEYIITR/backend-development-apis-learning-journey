-- Basic SELECT.
SELECT
    id,
    name,
    email,
    salary
FROM employees;

-- Projection: retrieve only the columns needed by the application.
SELECT
    name,
    salary
FROM employees;

-- Filtering with WHERE.
SELECT
    id,
    name,
    salary
FROM employees
WHERE salary >= 110000
ORDER BY salary DESC;

-- Multiple predicates.
SELECT
    name,
    salary,
    department_id
FROM employees
WHERE salary >= 90000
  AND salary < 130000
  AND department_id IN (1, 3)
ORDER BY salary DESC;

-- Pattern filtering.
SELECT
    name,
    email
FROM employees
WHERE name ILIKE '%a%'
ORDER BY name;

-- INNER JOIN between employees and departments.
SELECT
    e.id,
    e.name AS employee,
    d.name AS department,
    e.salary
FROM employees AS e
INNER JOIN departments AS d
    ON d.id = e.department_id
ORDER BY d.name, e.name;

-- Many-to-many join through the association table.
SELECT
    p.name AS project,
    e.name AS employee,
    p.status
FROM projects AS p
INNER JOIN employee_projects AS ep
    ON ep.project_id = p.id
INNER JOIN employees AS e
    ON e.id = ep.employee_id
ORDER BY p.name, e.name;

-- JOIN plus filtering.
SELECT
    e.name,
    d.name AS department,
    e.salary
FROM employees AS e
INNER JOIN departments AS d
    ON d.id = e.department_id
WHERE d.name IN ('Engineering', 'Security')
  AND e.salary >= 100000
ORDER BY e.salary DESC;

-- ORDER BY with a deterministic tie-breaker.
SELECT
    id,
    name,
    salary
FROM employees
ORDER BY salary DESC, name ASC;

-- Global aggregation.
SELECT
    COUNT(*) AS employee_count,
    SUM(salary) AS salary_total,
    AVG(salary) AS average_salary,
    MIN(salary) AS minimum_salary,
    MAX(salary) AS maximum_salary
FROM employees;

-- GROUP BY department.
SELECT
    d.name AS department,
    COUNT(e.id) AS employee_count,
    SUM(e.salary) AS salary_total,
    ROUND(AVG(e.salary), 2) AS average_salary,
    MAX(e.salary) AS highest_salary
FROM departments AS d
INNER JOIN employees AS e
    ON e.department_id = d.id
GROUP BY d.id, d.name
ORDER BY average_salary DESC;

-- HAVING filters groups after aggregation.
SELECT
    d.name AS department,
    COUNT(e.id) AS employee_count,
    ROUND(AVG(e.salary), 2) AS average_salary
FROM departments AS d
INNER JOIN employees AS e
    ON e.department_id = d.id
GROUP BY d.id, d.name
HAVING AVG(e.salary) >= 100000
ORDER BY average_salary DESC;

-- Project assignment aggregation.
SELECT
    p.name AS project,
    COUNT(ep.employee_id) AS assigned_employees
FROM projects AS p
LEFT JOIN employee_projects AS ep
    ON ep.project_id = p.id
GROUP BY p.id, p.name
ORDER BY assigned_employees DESC, p.name;

-- Employees above the company-wide average.
SELECT
    e.id,
    e.name,
    e.salary
FROM employees AS e
WHERE e.salary > (
    SELECT AVG(salary)
    FROM employees
)
ORDER BY e.salary DESC;

-- EXISTS is useful when the question is whether at least one related
-- record satisfies a condition.
SELECT
    e.id,
    e.name
FROM employees AS e
WHERE EXISTS (
    SELECT 1
    FROM employee_projects AS ep
    INNER JOIN projects AS p
        ON p.id = ep.project_id
    WHERE ep.employee_id = e.id
      AND p.status = 'active'
)
ORDER BY e.name;

-- LIMIT/OFFSET pagination.
-- Stable ordering is required before slicing a result into pages.
SELECT
    id,
    name,
    salary
FROM employees
ORDER BY id
LIMIT 3
OFFSET 0;

SELECT
    id,
    name,
    salary
FROM employees
ORDER BY id
LIMIT 3
OFFSET 3;

-- Count query commonly paired with an API page query.
SELECT COUNT(*) AS total_matching_records
FROM employees
WHERE salary >= 90000;

-- The corresponding page query.
SELECT
    id,
    name,
    salary
FROM employees
WHERE salary >= 90000
ORDER BY id
LIMIT 3
OFFSET 0;

-- A realistic reporting query combining JOIN, filtering, ordering,
-- aggregation, and a result limit.
SELECT
    d.name AS department,
    COUNT(e.id) AS employee_count,
    ROUND(AVG(e.salary), 2) AS average_salary,
    MAX(e.salary) AS highest_salary
FROM departments AS d
INNER JOIN employees AS e
    ON e.department_id = d.id
WHERE e.salary >= 80000
GROUP BY d.id, d.name
HAVING COUNT(e.id) >= 1
ORDER BY average_salary DESC
LIMIT 5;

