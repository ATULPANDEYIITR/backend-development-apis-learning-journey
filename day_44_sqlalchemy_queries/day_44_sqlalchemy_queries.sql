-- PostgreSQL-compatible relational model for studying the query patterns
-- represented by SQLAlchemy:
-- SELECT, filtering, JOIN, ORDER BY, aggregation, and pagination.

DROP TABLE IF EXISTS employee_projects;
DROP TABLE IF EXISTS projects;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS departments;

CREATE TABLE departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE employees (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(200) NOT NULL UNIQUE,
    salary NUMERIC(12, 2) NOT NULL CHECK (salary >= 0),
    joined_at TIMESTAMP NOT NULL,
    department_id INTEGER NOT NULL,
    CONSTRAINT fk_employee_department
        FOREIGN KEY (department_id)
        REFERENCES departments(id)
        ON DELETE RESTRICT
);

CREATE TABLE projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    budget NUMERIC(14, 2) NOT NULL CHECK (budget >= 0),
    status VARCHAR(30) NOT NULL,
    CONSTRAINT chk_project_status
        CHECK (status IN ('active', 'completed', 'paused'))
);

CREATE TABLE employee_projects (
    employee_id INTEGER NOT NULL,
    project_id INTEGER NOT NULL,
    PRIMARY KEY (employee_id, project_id),
    CONSTRAINT fk_assignment_employee
        FOREIGN KEY (employee_id)
        REFERENCES employees(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_assignment_project
        FOREIGN KEY (project_id)
        REFERENCES projects(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_employees_department
    ON employees(department_id);

CREATE INDEX idx_employees_salary
    ON employees(salary);

CREATE INDEX idx_employees_joined_at
    ON employees(joined_at);

CREATE INDEX idx_employee_projects_project
    ON employee_projects(project_id);

