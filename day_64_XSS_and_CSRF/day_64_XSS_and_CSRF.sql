-- ---------------------------------------------------------------------------
-- Workflow examples and validation tests
-- ---------------------------------------------------------------------------

BEGIN;

-- Valid request: the submitted digest and origin match the active session.
SELECT *
FROM try_add_comment(
    '10000000-0000-4000-8000-000000000001',
    1,
    'https://portal.example.test',
    decode(repeat('b2', 32), 'hex'),
    '<script>alert(1)</script>'
);

-- Stored content remains untrusted. Rendering code must HTML-encode it.
-- A successful CSRF check does not make submitted content safe.

-- Invalid token: the request is rejected and an audit event is recorded.
SELECT *
FROM try_add_comment(
    '10000000-0000-4000-8000-000000000001',
    1,
    'https://portal.example.test',
    decode(repeat('c3', 32), 'hex'),
    'This content must not be stored'
);

-- Foreign Origin: the request is rejected.
SELECT *
FROM try_add_comment(
    '10000000-0000-4000-8000-000000000001',
    1,
    'https://attacker.example',
    decode(repeat('b2', 32), 'hex'),
    'This content must not be stored'
);

-- Invalid body: the request is rejected before insertion.
SELECT *
FROM try_add_comment(
    '10000000-0000-4000-8000-000000000001',
    1,
    'https://portal.example.test',
    decode(repeat('b2', 32), 'hex'),
    '   '
);

COMMIT;

-- Cookie behavior: Lax blocks cross-site POST but permits a top-level GET.
SELECT
    cookie_would_be_sent(
        'Lax', TRUE, TRUE, 'cross-site', 'POST', FALSE
    ) AS lax_cross_site_post,
    cookie_would_be_sent(
        'Lax', TRUE, TRUE, 'cross-site', 'GET', TRUE
    ) AS lax_cross_site_top_level_get,
    cookie_would_be_sent(
        'Strict', TRUE, TRUE, 'cross-site', 'GET', TRUE
    ) AS strict_cross_site_get,
    cookie_would_be_sent(
        'None', TRUE, TRUE, 'cross-site', 'POST', FALSE
    ) AS none_cross_site_post;

-- Eligibility check for a particular CSRF-protected operation.
SELECT csrf_request_allowed(
    '10000000-0000-4000-8000-000000000001',
    1,
    'https://portal.example.test',
    decode(repeat('b2', 32), 'hex')
) AS valid_request_eligible;

-- Retrieval: untrusted content and its moderation state.
SELECT
    comment_id,
    user_id,
    moderation_status,
    body,
    created_at
FROM user_comments
ORDER BY created_at DESC;

-- Review inventory: markup characters require contextual review;
-- their presence is not a reliable vulnerability classification.
SELECT *
FROM untrusted_comment_inventory
ORDER BY created_at DESC;

-- Aggregation: security event counts by type.
SELECT *
FROM security_event_metrics
ORDER BY event_count DESC;

-- CTE-based reporting: recent failed CSRF attempts.
WITH recent_rejections AS (
    SELECT
        event_id,
        user_id,
        event_details,
        occurred_at
    FROM security_events
    WHERE event_type = 'csrf_rejected'
      AND occurred_at >= now() - interval '24 hours'
)
SELECT
    user_id,
    count(*) AS rejected_request_count,
    max(occurred_at) AS most_recent_rejection
FROM recent_rejections
GROUP BY user_id
ORDER BY rejected_request_count DESC;

-- Session maintenance. Expired sessions are revoked and audited.
CALL revoke_expired_sessions(now());

-- Active session retrieval after maintenance.
SELECT *
FROM active_sessions
ORDER BY expires_at;

-- Cookie configuration retrieval.
SELECT
    policy_name,
    cookie_name,
    same_site,
    secure,
    http_only,
    cookie_path,
    max_age_seconds
FROM cookie_policies;

-- Verify audit records created by accepted and rejected operations.
SELECT
    event_id,
    event_type,
    user_id,
    event_details,
    occurred_at
FROM security_events
ORDER BY occurred_at DESC, event_id DESC;
