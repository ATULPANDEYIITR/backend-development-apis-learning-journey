-- Defensive web security model: XSS, CSRF, sessions, cookies, and SameSite.
-- The application must generate cryptographic digests and perform HTML encoding.
-- This database stores untrusted text; it does not make text safe for HTML output.

CREATE SCHEMA IF NOT EXISTS web_security_lab;
SET search_path TO web_security_lab, public;

-- ---------------------------------------------------------------------------
-- Identity and session records
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS app_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    user_role TEXT NOT NULL DEFAULT 'member'
        CHECK (user_role IN ('member', 'moderator', 'security_admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_sessions (
    session_id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id) ON DELETE CASCADE,

    -- Store SHA-256 digests, not the browser's raw session cookie or CSRF token.
    -- The application computes these with a suitable cryptographic library.
    session_key_digest BYTEA NOT NULL
        CHECK (octet_length(session_key_digest) = 32),
    csrf_token_digest BYTEA NOT NULL
        CHECK (octet_length(csrf_token_digest) = 32),

    expected_origin TEXT NOT NULL
        CHECK (expected_origin ~ '^https://[^/]+$'),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,

    CHECK (expires_at > issued_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_app_sessions_key_digest
    ON app_sessions(session_key_digest);

CREATE INDEX IF NOT EXISTS ix_app_sessions_user_expiry
    ON app_sessions(user_id, expires_at)
    WHERE revoked_at IS NULL;

-- ---------------------------------------------------------------------------
-- Cookie configuration
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS cookie_policies (
    policy_name TEXT PRIMARY KEY,
    cookie_name TEXT NOT NULL,
    same_site TEXT NOT NULL
        CHECK (same_site IN ('Strict', 'Lax', 'None')),
    secure BOOLEAN NOT NULL,
    http_only BOOLEAN NOT NULL DEFAULT TRUE,
    cookie_path TEXT NOT NULL DEFAULT '/'
        CHECK (cookie_path LIKE '/%' AND position(';' IN cookie_path) = 0),
    max_age_seconds INTEGER NOT NULL CHECK (max_age_seconds >= 0),

    -- Browsers require Secure when SameSite=None is used.
    CHECK (same_site <> 'None' OR secure = TRUE)
);

-- ---------------------------------------------------------------------------
-- Stored content and security events
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS user_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    session_id UUID NOT NULL REFERENCES app_sessions(session_id),
    body TEXT NOT NULL CHECK (
        char_length(body) BETWEEN 1 AND 5000
        AND length(body) > 0
    ),
    moderation_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (moderation_status IN ('pending', 'approved', 'hidden')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_comments_status_created
    ON user_comments(moderation_status, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_comments_user_created
    ON user_comments(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS security_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL CHECK (
        event_type IN (
            'csrf_rejected',
            'comment_created',
            'input_rejected',
            'session_revoked'
        )
    ),
    user_id BIGINT REFERENCES app_users(user_id) ON DELETE SET NULL,
    session_id UUID REFERENCES app_sessions(session_id) ON DELETE SET NULL,
    event_details JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_security_events_type_time
    ON security_events(event_type, occurred_at DESC);

CREATE INDEX IF NOT EXISTS ix_security_events_details
    ON security_events USING GIN(event_details);

-- ---------------------------------------------------------------------------
-- CSRF validation
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION csrf_request_allowed(
    p_session_id UUID,
    p_user_id BIGINT,
    p_request_origin TEXT,
    p_token_digest BYTEA,
    p_now TIMESTAMPTZ DEFAULT now()
)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
AS $$
    SELECT COALESCE(
        p_token_digest IS NOT NULL
        AND octet_length(p_token_digest) = 32
        AND EXISTS (
            SELECT 1
            FROM app_sessions AS s
            WHERE s.session_id = p_session_id
              AND s.user_id = p_user_id
              AND s.expected_origin = p_request_origin
              AND s.csrf_token_digest = p_token_digest
              AND s.revoked_at IS NULL
              AND s.expires_at > p_now
        ),
        FALSE
    );
$$;

-- ---------------------------------------------------------------------------
-- Browser cookie behavior
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION cookie_would_be_sent(
    p_same_site TEXT,
    p_secure BOOLEAN,
    p_request_is_tls BOOLEAN,
    p_site_relation TEXT,
    p_method TEXT,
    p_top_level_navigation BOOLEAN
)
RETURNS BOOLEAN
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    v_method TEXT := upper(p_method);
BEGIN
    IF p_same_site NOT IN ('Strict', 'Lax', 'None') THEN
        RAISE EXCEPTION 'Unsupported SameSite value: %', p_same_site;
    END IF;

    IF p_site_relation NOT IN ('same-site', 'cross-site') THEN
        RAISE EXCEPTION 'Invalid site relation: %', p_site_relation;
    END IF;

    IF p_secure AND NOT p_request_is_tls THEN
        RETURN FALSE;
    END IF;

    IF p_site_relation = 'same-site' THEN
        RETURN TRUE;
    END IF;

    IF p_same_site = 'Strict' THEN
        RETURN FALSE;
    ELSIF p_same_site = 'Lax' THEN
        RETURN p_top_level_navigation
            AND v_method IN ('GET', 'HEAD');
    ELSE
        -- The table constraint separately enforces Secure for SameSite=None.
        RETURN p_secure;
    END IF;
END;
$$;

-- ---------------------------------------------------------------------------
-- Session consistency and audit triggers
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION enforce_comment_session()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_session_user_id BIGINT;
    v_expires_at TIMESTAMPTZ;
    v_revoked_at TIMESTAMPTZ;
BEGIN
    SELECT s.user_id, s.expires_at, s.revoked_at
      INTO v_session_user_id, v_expires_at, v_revoked_at
      FROM app_sessions AS s
     WHERE s.session_id = NEW.session_id
     FOR KEY SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Comment session does not exist';
    END IF;

    IF v_session_user_id <> NEW.user_id THEN
        RAISE EXCEPTION 'Comment user does not own the session';
    END IF;

    IF v_revoked_at IS NOT NULL OR v_expires_at <= now() THEN
        RAISE EXCEPTION 'Comment session is expired or revoked';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_enforce_comment_session ON user_comments;

CREATE TRIGGER trg_enforce_comment_session
BEFORE INSERT ON user_comments
FOR EACH ROW
EXECUTE FUNCTION enforce_comment_session();

CREATE OR REPLACE FUNCTION audit_comment_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO security_events (
        event_type,
        user_id,
        session_id,
        event_details
    )
    VALUES (
        'comment_created',
        NEW.user_id,
        NEW.session_id,
        jsonb_build_object(
            'comment_id', NEW.comment_id,
            'moderation_status', NEW.moderation_status
        )
    );

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_audit_comment_insert ON user_comments;

CREATE TRIGGER trg_audit_comment_insert
AFTER INSERT ON user_comments
FOR EACH ROW
EXECUTE FUNCTION audit_comment_insert();

-- ---------------------------------------------------------------------------
-- Application-facing comment submission workflow
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION try_add_comment(
    p_session_id UUID,
    p_user_id BIGINT,
    p_request_origin TEXT,
    p_csrf_token_digest BYTEA,
    p_body TEXT
)
RETURNS TABLE (
    accepted BOOLEAN,
    reason TEXT,
    new_comment_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_comment_id BIGINT;
BEGIN
    IF p_body IS NULL
       OR btrim(p_body) = ''
       OR char_length(p_body) > 5000
       OR position(chr(0) IN p_body) > 0 THEN

        INSERT INTO security_events (
            event_type,
            user_id,
            event_details
        )
        VALUES (
            'input_rejected',
            p_user_id,
            jsonb_build_object('reason', 'invalid_comment_body')
        );

        RETURN QUERY
        SELECT FALSE, 'invalid_comment_body'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    IF NOT csrf_request_allowed(
        p_session_id,
        p_user_id,
        p_request_origin,
        p_csrf_token_digest
    ) THEN

        -- The rejected event is committed with the caller's transaction.
        -- This function returns a decision instead of raising an exception,
        -- which would roll back the audit record.
        INSERT INTO security_events (
            event_type,
            user_id,
            event_details
        )
        VALUES (
            'csrf_rejected',
            p_user_id,
            jsonb_build_object(
                'reason', 'csrf_validation_failed',
                'origin', p_request_origin
            )
        );

        RETURN QUERY
        SELECT FALSE, 'csrf_validation_failed'::TEXT, NULL::BIGINT;
        RETURN;
    END IF;

    INSERT INTO user_comments (
        user_id,
        session_id,
        body,
        moderation_status
    )
    VALUES (
        p_user_id,
        p_session_id,
        p_body,
        'pending'
    )
    RETURNING comment_id INTO v_comment_id;

    RETURN QUERY
    SELECT TRUE, 'accepted'::TEXT, v_comment_id;
END;
$$;

-- ---------------------------------------------------------------------------
-- Session maintenance procedure
-- ---------------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE revoke_expired_sessions(
    p_now TIMESTAMPTZ DEFAULT now()
)
LANGUAGE plpgsql
AS $$
BEGIN
    WITH expired AS (
        UPDATE app_sessions
           SET revoked_at = p_now
         WHERE revoked_at IS NULL
           AND expires_at <= p_now
        RETURNING session_id, user_id
    )
    INSERT INTO security_events (
        event_type,
        user_id,
        session_id,
        event_details,
        occurred_at
    )
    SELECT
        'session_revoked',
        user_id,
        session_id,
        jsonb_build_object('reason', 'expired'),
        p_now
    FROM expired;
END;
$$;

-- ---------------------------------------------------------------------------
-- Reporting views
-- ---------------------------------------------------------------------------

CREATE OR REPLACE VIEW active_sessions AS
SELECT
    s.session_id,
    s.user_id,
    s.issued_at,
    s.expires_at,
    s.expected_origin
FROM app_sessions AS s
WHERE s.revoked_at IS NULL
  AND s.expires_at > now();

CREATE OR REPLACE VIEW comment_moderation_queue AS
SELECT
    c.comment_id,
    c.user_id,
    c.body,
    char_length(c.body) AS body_length,
    c.created_at
FROM user_comments AS c
WHERE c.moderation_status = 'pending';

-- This is a review aid, not an XSS detector. The presence of markup
-- characters does not prove that content is executable or malicious.
CREATE OR REPLACE VIEW untrusted_comment_inventory AS
SELECT
    c.comment_id,
    c.user_id,
    c.moderation_status,
    char_length(c.body) AS body_length,
    position('<' IN c.body) > 0 AS contains_less_than_character,
    c.created_at
FROM user_comments AS c;

CREATE OR REPLACE VIEW security_event_metrics AS
SELECT
    event_type,
    count(*) AS event_count,
    min(occurred_at) AS first_seen,
    max(occurred_at) AS last_seen
FROM security_events
GROUP BY event_type;

